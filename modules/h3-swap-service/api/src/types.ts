export type JobStatus = "queued" | "running" | "succeeded" | "failed";
export type WorkerState = "booting" | "idle" | "busy";

export interface UserRow {
  id: string;
  email: string | null;
  balance_cents: number;
  created_at: string;
}

export interface ApiKeyRow {
  key_hash: string;
  user_id: string;
  created_at: string;
}

export interface JobRow {
  id: string;
  user_id: string;
  status: JobStatus;
  duration_s: number;
  reserved_cents: number;
  /** Worker id that holds the claim (set on claim, cleared on release). */
  worker_id: string | null;
  /** JSON of the queue message, kept so the job can be requeued after a lost worker. */
  message: string | null;
  charged_cents: number;
  source_key: string;
  output_key: string | null;
  error: string | null;
  attempts: number;
  gpu_seconds: number | null;
  wall_seconds: number | null;
  created_at: string;
  started_at: string | null;
  finished_at: string | null;
}

export interface WorkerRow {
  /** Worker id generated by the autoscaler (w-<12 hex>); the worker reports this as instance_id. */
  instance_id: string;
  /** Vast contract id, NULL until the create call returns (or for rows created by heartbeat). */
  /** Provider ref: Vast contract id, or the Salad container name. NULL until stored. */
  provider_ref: string | null;
  provider: string;
  state: WorkerState;
  created_at: string;
  last_heartbeat_at: string | null;
  idle_seconds: number;
  jobs_done: number;
}

export interface CharacterMessage {
  image_key: string;
  replace_description: string;
}

// Queue message body (CONTRACT section 4).
export interface JobMessage {
  job_id: string;
  user_id: string;
  created_at: string;
  tier: "768p";
  duration_s: number;
  fps: 24;
  source_key: string;
  characters: CharacterMessage[];
  prompt_extra: string | null;
  seed: number | null;
}
