"""UGC track: the deterministic half of the generative UGC pipeline (docs: ugc/README.md, ADR-0004).

Images, voices and clips are generated by external models (GPT Image, Seedance, Krea) and are NOT reproducible, so
they stay outside `render`. This module only lists the character pack and builds/validates the Seedance prompt from
the fixed skeleton, so the same pack + app + line always yields the same prompt.
"""
from __future__ import annotations

import json
from pathlib import Path

from . import paths

PACK_REL = "ugc/pack.json"
SCHEMA_REL = "ugc/pack.schema.json"
SEEDANCE_TEMPLATE = (
    "authentic UGC clip, handheld front camera selfie, 9:16. keep the character identical to the reference images. "
    "{local}. {ele}'s already holding {dele} phone with {app} open. delivery: {entrega}. {ele} says exactly: \"{fala}\" "
    "around second 5 {ele} glances down at the screen, {reacao}. one continuous action. exactly one phone in the entire scene. "
    "no text or captions. iPhone front camera 23mm equivalent, slight handheld drift, built-in mic, no music"
)
PRONOUNS = {"m": ("he", "his"), "f": ("she", "her")}
# 22-28 words for a 7 s clip (~3.5 words/s): Seedance stretches the line to fill the clip, so outside this band it
# comes out rushed or leaves the character staring at the lens.
WPS_MIN, WPS_MAX = 22 / 7, 28 / 7
DEFAULT_DURATION_S = 7.0


class UgcError(Exception):
    pass


def load_pack(home: Path | None = None) -> dict:
    import jsonschema
    h = home or paths.home()
    pack = json.loads((h / PACK_REL).read_text(encoding="utf8"))
    schema = json.loads((h / SCHEMA_REL).read_text(encoding="utf8"))
    errs = sorted(jsonschema.Draft202012Validator(schema).iter_errors(pack), key=lambda e: list(e.path))
    if errs:
        raise UgcError(f"{PACK_REL}: " + "; ".join(f"{'/'.join(map(str, e.path)) or '<raiz>'}: {e.message}" for e in errs))
    ids = [c["id"] for c in pack["personagens"]]
    dup = sorted({i for i in ids if ids.count(i) > 1})
    if dup:
        raise UgcError(f"{PACK_REL}: ids duplicados: {', '.join(dup)}")
    return pack


def word_range(duration_s: float) -> tuple[int, int]:
    return round(WPS_MIN * duration_s), round(WPS_MAX * duration_s)


def word_count(text: str) -> int:
    return len(text.split())


def find(pack: dict, char_id: str) -> dict:
    for c in pack["personagens"]:
        if c["id"] == char_id:
            return c
    raise UgcError(f"personagem desconhecido: {char_id!r} (ids: {', '.join(c['id'] for c in pack['personagens'])})")


def build_prompt(char: dict, app: str, fala: str | None = None, duration_s: float = DEFAULT_DURATION_S) -> dict:
    """Seedance prompt for one character. Returns {id, prompt, palavras, faixa, avisos}; `fala` overrides the example line."""
    app = app.strip()
    if not app:
        raise UgcError("--app: nome do app/marca vazio")
    if duration_s <= 0:
        raise UgcError("--duracao deve ser > 0")
    line = " ".join((fala if fala is not None else char["fala"]).split())
    if not line:
        raise UgcError("fala vazia")
    if '"' in line:
        raise UgcError('fala não pode conter aspas ("): o prompt delimita a fala com aspas')
    ele, dele = PRONOUNS[char["genero"]]
    prompt = SEEDANCE_TEMPLATE.format(local=char["local"], ele=ele, dele=dele, app=app, entrega=char["entrega"], fala=line,
                                      reacao=char["reacao"])
    n, (lo, hi) = word_count(line), word_range(duration_s)
    avisos = []
    if n < lo:
        avisos.append(f"fala com {n} palavras < {lo}: em {duration_s:g} s o personagem fica encarando a câmera")
    elif n > hi:
        avisos.append(f"fala com {n} palavras > {hi}: em {duration_s:g} s a fala sai apressada")
    return {"id": char["id"], "prompt": prompt, "palavras": n, "faixa": [lo, hi], "avisos": avisos}
